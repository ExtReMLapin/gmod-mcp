#!/usr/bin/env python3
"""Generates tests/native/slot_fixtures.h: the first bytes of the functions behind the vtable slots the module calls, read from the
real game binaries (docs/REVERSE.md, "Slot checks"). The native tests (tests/native/test_slotcheck.cpp) run the layout decisions on
these bytes, so a recompiled or moved function is caught against what the games really contain.

  python tests/native/tools/gen_slot_fixtures.py OUT.h --old DIR --new DIR --engine-a engine.dll --engine-b engine.dll

DIR holds lua_shared.dll and filesystem_stdio.dll of one game build ("old": IAppSystem with 5 slots, "new": the x86-64 build of
2026-11-19 with 9). Needs `pip install pefile capstone`. The vtables are found through the MSVC RTTI of CLuaShared, CLuaInterface,
CFileSystem_Stdio, CEngineClient and CNetChan.
"""
import argparse, hashlib, os, re, struct, sys
import capstone, pefile

def load(path):
    pe = pefile.PE(path, fast_load=True)
    data = open(path,'rb').read()
    return pe, data
def sections(pe):
    return [(s.Name.rstrip(b'\0').decode(), s.VirtualAddress, s.Misc_VirtualSize, s.PointerToRawData, s.SizeOfRawData) for s in pe.sections]
def rva2off(pe, rva): return pe.get_offset_from_rva(rva)
def find_vtables(path, clsname):
    pe, data = load(path)
    pat = ('.?AV%s@@' % clsname).encode()
    res = []
    for m in re.finditer(re.escape(pat), data):
        td_off = m.start() - 16
        # type descriptor RVA
        try:
            td_rva = pe.get_rva_from_offset(td_off)
        except Exception: continue
        # find COLs: signature 1, offset, cdoffset, typedesc rva (at +12)
        for sname, va, vs, raw, rs in sections(pe):
            if sname not in ('.rdata',): continue
            blob = data[raw:raw+rs]
            i = 0
            needle = struct.pack('<I', td_rva)
            while True:
                j = blob.find(needle, i)
                if j < 0: break
                i = j + 1
                if j < 12 or (j-12) % 4: continue
                sig, off, cd, tdr, chd, selfr = struct.unpack_from('<IIIIII', blob, j-12) if j-12+24 <= len(blob) else (9,)*6
                if sig != 1: continue
                col_rva = va + j - 12
                col_va = pe.OPTIONAL_HEADER.ImageBase + col_rva
                # vtable pointer to COL
                needle2 = struct.pack('<Q', col_va)
                k = 0
                while True:
                    q = blob.find(needle2, k)
                    if q < 0: break
                    k = q + 1
                    res.append((off, pe.OPTIONAL_HEADER.ImageBase + va + q + 8))
    return pe, data, res
def slots(pe, data, vt_va, n):
    base = pe.OPTIONAL_HEADER.ImageBase
    out = []
    for i in range(n):
        p = struct.unpack_from('<Q', data, rva2off(pe, vt_va - base + 8*i))[0]
        out.append(p)
    return out
def code(pe, data, va, n=48):
    base = pe.OPTIONAL_HEADER.ImageBase
    try: o = rva2off(pe, va - base)
    except Exception: return b''
    return data[o:o+n]
def dis(b, va):
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    return [(hex(i.address), i.mnemonic, i.op_str) for i in md.disasm(b, va)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--old', required=True)
    ap.add_argument('--new', required=True)
    ap.add_argument('--engine-a', required=True)
    ap.add_argument('--engine-b', required=True)
    a = ap.parse_args()
    builds = {
        'luashared': [('old', os.path.join(a.old, 'lua_shared.dll')), ('new', os.path.join(a.new, 'lua_shared.dll'))],
        'filesystem': [('old', os.path.join(a.old, 'filesystem_stdio.dll')), ('new', os.path.join(a.new, 'filesystem_stdio.dll'))],
        'engine': [('a', a.engine_a), ('b', a.engine_b)],
    }

    def sha(p):
        return hashlib.sha256(open(p, 'rb').read()).hexdigest()

    def vtable(path, cls, n):
        pe, data, res = find_vtables(path, cls)
        off, v = res[0]
        return pe, data, slots(pe, data, v, n)

    out = []
    out.append('// GENERATED by tests/native/tools/gen_slot_fixtures.py from the real game binaries; do not edit by hand.\n'
               '// The first bytes of the functions behind the vtable slots the module calls, read from the files on disk (sha256 below):\n'
               '//   lua_shared / filesystem_stdio "old" = IAppSystem with 5 slots, "new" = the x86-64 build of 2026-11-19 (9 slots);\n'
               '//   engine "a" / "b" = two engine.dll builds. docs/REVERSE.md, "Slot checks".\n'
               '#pragma once\n#include <cstdint>\n#include <map>\n#include <string>\n#include <vector>\n\nnamespace slotfx {\n\n'
               'using Hex = const char *;\n'
               'inline std::vector<uint8_t> bytes(Hex h) {\n    std::vector<uint8_t> b;\n'
               '    for (size_t i = 0; h[i] && h[i + 1]; i += 2) b.push_back((uint8_t)std::stoi(std::string(h + i, 2), nullptr, 16));\n    return b;\n}\n\n'
               'struct Slots {\n    const char *label, *file_sha256;\n    std::map<int, Hex> code;  // vtable slot -> the first bytes of its function\n};\n')
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)

    def emit_slots(name, label, path, cls, n, nbytes, big=None):
        pe, data, sl = vtable(path, cls, n)
        lines = ['inline const Slots %s = {"%s", "%s", {' % (name, label, sha(path))]
        for i, p in enumerate(sl):
            lines.append('    {%d, "%s"},' % (i, code(pe, data, p, (big or {}).get(i, nbytes)).hex()))
        lines.append('}};\n')
        out.append('\n'.join(lines))
        return pe, data, sl

    big = {9: 0x60, 10: 0x40, 17: 0x200, 16: 0x200, 18: 0x200, 8: 0x100, 7: 0x100, 14: 0x100, 15: 0x100}
    for lab, path in builds['luashared']:
        pe, data, sl = emit_slots('luashared_' + lab, lab, path, 'CLuaShared', 19, 0x40, big)
        b = code(pe, data, sl[9], 0x60)
        strs = []
        for i in md.disasm(b, sl[9]):
            if i.mnemonic == 'lea' and 'rip' in i.op_str:
                m = re.search(r'rip \+ (0x[0-9a-f]+)', i.op_str)
                tgt = i.address + i.size + int(m.group(1), 16)
                o = pe.get_offset_from_rva(tgt - pe.OPTIONAL_HEADER.ImageBase)
                strs.append((tgt - sl[9], data[o:o + 64].split(b'\0')[0].decode()))
            if i.mnemonic == 'int3':
                break
        out.append('// MountLua (slot 9) string references: offset from the function start -> text at that address.\n'
                   'inline const std::map<int64_t, const char *> luashared_%s_strings = {%s};\n'
                   % (lab, ', '.join('{%d, "%s"}' % (r, s) for r, s in strs)))
        pe2, data2, sl2 = vtable(path, 'CLuaInterface', 4)
        out.append('inline const char *luainterface_%s_top = "%s";  // CLuaInterface vtable slot 0 (ILuaBase::Top)\n'
                   % (lab, code(pe2, data2, sl2[0], 16).hex()))
    for lab, path in builds['filesystem']:
        emit_slots('filesystem_' + lab, lab, path, 'CFileSystem_Stdio', 20, 0x10)
    for lab, path in builds['engine']:
        emit_slots('engineclient_' + lab, lab, path, 'CEngineClient', 80, 0x60, {72: 0x10})
        emit_slots('netchan_' + lab, lab, path, 'CNetChan', 12, 0x10)
    out.append('\n}  // namespace slotfx\n')
    open(a.out, 'w', newline='\n').write('\n'.join(out))


if __name__ == '__main__':
    main()
